"""Calibrate reusable Bloom taps against four Gaussian scales."""
import os
from pathlib import Path

os.environ["OPENBLAS_NUM_THREADS"] = "1"
os.environ["OMP_NUM_THREADS"] = "1"

import numpy as np
from scipy.optimize import minimize
from scipy.sparse import csr_matrix

LEVELS = 4
# Weight the four-scale calibration proxy. The runtime weights its eight
# octaves independently of this fit.
LAYER_WEIGHTS = (.125, .125, .125, .625)
SIGMAS = np.sqrt(4.0 ** np.arange(1, LEVELS + 1) - 1)
SIZE = 224
CENTER = SIZE // 2
RADIUS = 64
FIT_PHASES = [(0, 0), (0, 3), (1, 1), (1, 4), (2, 2),
              (2, 5), (3, 5), (4, 4), (5, 5), (7, 7)]
DIAGONALS = [(-1, -1), (-1, 1), (1, -1), (1, 1)]
AXES = [(-1, 0), (1, 0), (0, -1), (0, 1)]


def taps(parameters):
    center_weight, axial_offset, diagonal_offset, diagonal_share = parameters
    # Preserve the first moment for each decimation parity. The centered
    # sample shifts the even impulse by +.5, and the diagonal pair by 1.5-2*d.
    down_offset = .75 + .25 * center_weight / (1 - center_weight)
    down = [(0, 0, center_weight)]
    down += [(x * down_offset, y * down_offset, (1 - center_weight) / 4)
             for x, y in DIAGONALS]
    up = [(x * axial_offset, y * axial_offset, (1 - diagonal_share) / 4) for x, y in AXES]
    up += [(x * diagonal_offset, y * diagonal_offset, diagonal_share / 4)
           for x, y in DIAGONALS]
    return down, up


def interpolation(size, positions):
    low = np.floor(positions).astype(int)
    cols = np.stack((low, low + 1), axis=1)
    frac = positions - low
    weights = np.stack((1 - frac, frac), axis=1)
    rows = np.broadcast_to(np.arange(len(positions))[:, None], cols.shape)
    valid = (cols >= 0) & (cols < size) & (weights != 0)
    return csr_matrix((weights[valid], (rows[valid], cols[valid])),
                      shape=(len(positions), size))


def pyramid(parameters):
    down, up = taps(parameters)
    sizes = [SIZE >> level for level in range(LEVELS + 1)]
    stages = list(zip(sizes, sizes[1:])) + list(zip(sizes[:0:-1], sizes[-2::-1]))
    operations = []
    for i, (src, dst) in enumerate(stages):
        if i < LEVELS:
            centers, kernel = 2 * np.arange(dst) + .5, down
        else:
            centers, kernel = .5 * np.arange(dst) - .25, up
        matrices = {o: interpolation(src, centers + o)
                    for o in {offset for x, y, _ in kernel for offset in (x, y)}}
        operations.append([(matrices[x], matrices[y], w) for x, y, w in kernel])
    return operations


def response(operations, phase):
    y, x = (CENTER + p for p in phase)
    image = np.zeros((SIZE, SIZE))
    image[y, x] = 1
    downsampled = []
    for i, stage in enumerate(operations):
        image = sum(w * (mx @ (my @ image).T).T for mx, my, w in stage)
        if i < LEVELS:
            downsampled.append(image)
            if i == LEVELS - 1:
                image = image * LAYER_WEIGHTS[-1]
        else:
            level = 2 * LEVELS - i - 1
            if level:
                image += downsampled[level - 1] * LAYER_WEIGHTS[level - 1]
    return image, y, x


def emit(parameters, fit_error, held_error):
    output = Path(__file__).resolve().parents[1] / "shaders/techniques/BloomTaps.glsl"
    down, up = taps(parameters)
    lines = [
        "// Generated by scripts/fit-bloom.py.",
        f"// Four-scale calibration relative L2 means: fit {fit_error:.6f}, held-out {held_error:.6f}.",
        "",
        "vec3 bloom_filter(vec2 center, vec4 tile) {",
        "    #ifdef BLOOM_DOWNSAMPLE",
    ]
    for index, kernel in enumerate((down, up)):
        if index:
            lines.append("    #else")
        for i, (x, y, w) in enumerate(kernel):
            prefix = "vec3 result =" if i == 0 else "result +="
            lines.append(f"    {prefix} bloom_sample(center + vec2({x:.9f}, {y:.9f}), tile) * {w:.9f};")
    lines += ["    #endif", "    return result;", "}", ""]
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    axis = np.arange(-RADIUS, RADIUS + 1)
    target = np.zeros((len(axis), len(axis)))
    for weight, sigma in zip(LAYER_WEIGHTS, SIGMAS):
        g = np.exp(-.5 * (axis / sigma)**2) / (np.sqrt(2 * np.pi) * sigma)
        target += weight * np.outer(g, g)
    norm = np.linalg.norm(target)
    loss_weight = 1 / np.maximum(target, 1e-7)
    loss_norm = np.linalg.norm(target * np.sqrt(loss_weight))

    def residual(operations, phase):
        image, y, x = response(operations, phase)
        crop = image[y-RADIUS:y+RADIUS+1, x-RADIUS:x+RADIUS+1]
        return crop - target

    def loss(parameters):
        operations = pyramid(parameters)
        return np.mean([np.sum(loss_weight * residual(operations, phase)**2) / loss_norm**2
                        for phase in FIT_PHASES])

    # Start from the centroid-preserving single-scale fit.
    result = minimize(loss, [.08, 1.25, .451205115, .755144222],
                      method="L-BFGS-B",
                      bounds=[(.08, .6), (.3, 1.25), (.25, 1.25), (.08, .92)],
                      options={"maxiter":100, "ftol":1e-10, "eps":1e-6})
    if not result.success:
        raise RuntimeError(result.message)
    ops = pyramid(result.x)
    period = 2**LEVELS
    orbit = lambda p: tuple(sorted(min(a, period-1-a) for a in p))
    fit, held = [], []
    for y in range(period):
        for x in range(period):
            phase = (y, x)
            image, iy, ix = response(ops, phase)
            q = np.arange(SIZE)
            np.testing.assert_allclose(
                [image.sum(), image.sum(axis=0) @ q, image.sum(axis=1) @ q],
                [1., ix, iy], atol=1e-10, rtol=0)
            (fit if orbit(phase) in FIT_PHASES else held).append(
                np.linalg.norm(residual(ops, phase)) / norm)
    emit(result.x, np.mean(fit), np.mean(held))
    print(f"fit: {len(fit)} phases, mean {np.mean(fit):.6f}; "
          f"held: {len(held)} phases, mean {np.mean(held):.6f}, max {max(held):.6f}")
    print(result.x.tolist())


if __name__ == "__main__":
    main()
